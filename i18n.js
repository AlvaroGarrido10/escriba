// El documento offscreen no tiene chrome.i18n: allí vale navigator.language, que
// Chrome pone con su idioma. Sin ninguno de los dos (Node), español.
function idiomaNavegador() {
  let l = "";
  try { l = (chrome.i18n && chrome.i18n.getUILanguage && chrome.i18n.getUILanguage()) || ""; } catch (_) { /* sin chrome: Node */ }
  if (!l && typeof navigator !== "undefined" && navigator.language) l = navigator.language;
  return /^(es|ca|gl|eu)\b/i.test(l || "es") ? "es" : "en";
}
let IDIOMA_UI = typeof chrome !== "undefined" ? idiomaNavegador() : "es";
// Para fechas y números: toLocaleString(LOCALE_UI()). Es `function` y no
// `const` a propósito: exportar.js y comun.js la redeclaran con `var` para Node,
// y un `var` sobre un `const` global de otro script es un SyntaxError.
function LOCALE_UI() { return IDIOMA_UI === "en" ? "en-US" : "es-ES"; }

function t(clave, ...subs) {
  const tabla = TEXTOS[IDIOMA_UI] || TEXTOS.es;
  const txt = clave in tabla ? tabla[clave] : clave in TEXTOS.es ? TEXTOS.es[clave] : clave;
  return String(txt).replace(/\{(\d)\}/g, (m, i) => (subs[i - 1] !== undefined ? String(subs[i - 1]) : m));
}

function traducirPagina(raiz) {
  const r = raiz || document;
  for (const el of r.querySelectorAll("[data-i18n]")) el.textContent = t(el.dataset.i18n);
  for (const el of r.querySelectorAll("[data-i18n-html]")) el.innerHTML = t(el.dataset.i18nHtml);
  for (const el of r.querySelectorAll("[data-i18n-placeholder]")) el.placeholder = t(el.dataset.i18nPlaceholder);
  for (const el of r.querySelectorAll("[data-i18n-title]")) el.title = t(el.dataset.i18nTitle);
  for (const el of r.querySelectorAll("[data-i18n-aria-label]")) el.setAttribute("aria-label", t(el.dataset.i18nAriaLabel));
  if (r.documentElement) r.documentElement.lang = IDIOMA_UI;
}

// Fija el idioma con el valor de Opciones («auto», «es» o «en»). La usa el
// documento offscreen, que no tiene chrome.storage y recibe la preferencia con
// la configuración que le manda el service worker.
function ponIdiomaUI(valor) {
  IDIOMA_UI = valor === "es" || valor === "en" ? valor : idiomaNavegador();
  return IDIOMA_UI;
}

// Aplica lo elegido en Opciones y traduce la página.
async function cargarIdiomaUI() {
  try {
    const { idiomaUI } = await chrome.storage.sync.get({ idiomaUI: "auto" });
    ponIdiomaUI(idiomaUI);
  } catch (_) { /* sin storage (offscreen, Node): se queda el del navegador */ }
  if (typeof document !== "undefined") traducirPagina(document);
  return IDIOMA_UI;
}

